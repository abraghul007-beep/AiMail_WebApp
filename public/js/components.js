// Helpers
function esc(v = '') {
  return String(v).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function escAttr(v = '') {
  return esc(v);
}

function cleanSender(v = '') {
  const m = v.match(/^([^<]+)/);
  return m ? m[1].replace(/["']/g, '').trim() : v;
}

function initials(v = '') {
  const clean = v.replace(/<[^>]*>/g, '').replace(/["']/g, '').trim();
  const parts = clean.split(/[ @._-]/).filter(Boolean);
  if (parts.length >= 2) return (parts[0][0] + parts[1][0]).toUpperCase();
  return clean.slice(0, 2).toUpperCase() || 'U';
}

function formatDate(v) {
  if (!v) return '';
  const d = new Date(v);
  if (Number.isNaN(d.getTime())) return '';
  const now = new Date();
  if (d.toDateString() === now.toDateString()) {
    return d.toLocaleTimeString(undefined, { hour: 'numeric', minute: '2-digit' });
  }
  return d.toLocaleDateString(undefined, { month: 'short', day: 'numeric' });
}

function formatFull(v) {
  if (!v) return '';
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? esc(v) : d.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' });
}

function folderTitle(f) {
  return {
    INBOX: 'Inbox',
    STARRED: 'Starred',
    SENT: 'Sent',
    DRAFT: 'Drafts',
    ARCHIVE: 'Archive'
  }[f] || 'Inbox';
}

function summary(t = []) {
  const text = t.map(x => x.body || x.snippet || '').join(' ').replace(/\s+/g, ' ').trim();
  if (!text) return 'No conversation text found to summarize.';
  return text.length > 340 ? text.slice(0, 340) + '…' : text;
}